"""Render every measured planted readout and model-difference cell, without selection."""
import argparse
import hashlib
import itertools
import json
from pathlib import Path


def render(data, source_hash):
    if data['detection_status']!='measured':raise ValueError('Detection is not measured')
    rows=data['rows']
    behavior=data['behavior']
    verified='verified' if data['trait_verified'] else 'not verified'
    lenses=sorted(data['metadata']['label_tuned'])
    keys=[(r['lens'],r['layer'],r['mode'],r['read_mode']) for r in rows]
    expected=set(itertools.product(lenses,range(24),('on_policy','off_policy'),('lens_of_mean','mean_of_lens')))
    if len(keys)!=len(set(keys)) or set(keys)!=expected:
        raise ValueError('Incomplete or duplicate planted readout grid')
    if any(len(r['null_ranks'])!=1000 for r in rows):
        raise ValueError('Expected 1,000 null ranks per readout')
    for field in ('model_diff_faithfulness','behavior_model_diff_faithfulness'):
        if sorted(r['layer'] for r in data[field])!=list(range(24)):
            raise ValueError('Incomplete model-difference layer grid')
    lines=['# Qwen planted-organism detection: full conditional measurements','',
        f'Source SHA256: `{source_hash}`. Generated by `scripts/report_planted_detection.py`.','',
        f'The behavioral planting was **{verified}**: the paired effect was {behavior["difference"]:.6g},',
        f'95% prompt-bootstrap CI [{behavior["ci"][0]:.6g}, {behavior["ci"][1]:.6g}].',
        'Readouts alone cannot establish a successful behavioral planting. No graph',
        'results are included. No rows are selected or hidden based on rank or p-value.','',
        'Ranks are vocabulary ranks (smaller is better), not population estimates.',
        'The nominal p-values compare contrast ranks with 1,000 prompt-split control',
        'nulls; they are not corrected for this full grid and are not random-direction',
        'causal tests. Raw null samples remain in the JSON artifact. On-policy reads',
        'use each model’s own completions; off-policy reads use matched text.','',
        '## Absolute, contrastive, and model-difference ranks','',
        '| Lens | Label-tuned | Layer | Policy | Aggregation | Base absolute rank | Tuned absolute rank | Model-diff rank | Contrast rank | Nominal null p |',
        '|---|---|---:|---|---|---:|---:|---:|---:|---:|']
    def fmt(value):return 'unknown' if value is None else f'{value:.6g}' if isinstance(value,float) else str(value)
    for r in sorted(rows,key=lambda r:(r['lens'],r['layer'],r['mode'],r['read_mode'])):
        mode=r['read_mode'];absolute=r['absolute_ranks'][mode]
        values=[r['lens'],data['metadata']['label_tuned'][r['lens']],r['layer'],r['mode'],mode,
                absolute['base'],absolute['tuned'],r['model_diff_lens_rank'][mode],r['target_rank'],r['rank_upper_significance_p']]
        lines.append('| '+' | '.join(fmt(v) for v in values)+' |')
    lines+=['','## Base-model responses to model-difference perturbations','',
        'These R² values measure the base model’s antithetic response to tuned-minus-base',
        'residual perturbations. They do not measure the fraction of total behavioral',
        'trait variance explained. Intervals resample prompts. Final-layer identity',
        'structure is a separate explanation for high final-layer R².','',
        '| Context | Layer | R² | 95% CI |','|---|---:|---:|---|']
    for field,label in [('model_diff_faithfulness','WikiText'),('behavior_model_diff_faithfulness','Matched behavioral completion')]:
        for r in sorted(data[field],key=lambda r:r['layer']):
            lines.append(f"| {label} | {r['layer']} | {fmt(r['r2'])} | [{fmt(r['ci'][0])}, {fmt(r['ci'][1])}] |")
    return '\n'.join(lines)+'\n'


def main():
    p=argparse.ArgumentParser();p.add_argument('--input',default='artifacts/qwen-planted-detection.json');p.add_argument('--output',default='QWEN_PLANTED_RESULTS.md');args=p.parse_args()
    raw=Path(args.input).read_bytes();data=json.loads(raw)
    Path(args.output).write_text(render(data,hashlib.sha256(raw).hexdigest()))


if __name__=='__main__':main()
